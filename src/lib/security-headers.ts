/** Cabeçalhos de segurança. A CSP usa nonce por requisição (gerado no proxy). */

export function createNonce(): string {
  const bytes = new Uint8Array(16);
  crypto.getRandomValues(bytes);
  return btoa(String.fromCharCode(...bytes));
}

export function buildContentSecurityPolicy(options: {
  nonce: string;
  supabaseUrl: string;
  isDev: boolean;
}): string {
  const { nonce, supabaseUrl, isDev } = options;
  const connect = ["'self'", supabaseUrl].filter(Boolean).join(" ");
  return [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}' 'strict-dynamic'${isDev ? " 'unsafe-eval'" : ""}`,
    // Atributos style="" (posicionamento de componentes) exigem unsafe-inline; scripts não.
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' blob: data:",
    "font-src 'self'",
    `connect-src ${connect}`,
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join("; ");
}

